export function translateUiText(
  text: string,
  values?: Record<string, string | number>,
): string {
  const activePinia = getActivePinia();
  const persistedSettings =
    !activePinia && typeof localStorage !== 'undefined'
      ? localStorage.getItem('ftUISettings')
      : null;
  const persistedLanguage = persistedSettings
    ? (JSON.parse(persistedSettings) as { language?: string }).language
    : undefined;
  const language = activePinia
    ? useSettingsStore(activePinia).language
    : persistedLanguage === 'zh-CN'
      ? 'zh-CN'
      : 'en';
  const translated = language === 'zh-CN' ? (zhCN[text] ?? text) : text;
  return values
    ? translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
        String(values[key] ?? placeholder),
      )
    : translated;
}
